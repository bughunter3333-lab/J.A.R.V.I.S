"""Offline tests for the fine-tuning pipeline (training itself needs a GPU)."""
import pytest

import tools
from evals import compare
from training import build_dataset, install_model


@pytest.fixture(scope="module")
def examples():
    return build_dataset.build()


def test_dataset_never_contains_an_eval_question(examples):
    held_out = build_dataset.eval_questions()
    for ex in examples:
        assert build_dataset.norm(ex["messages"][1]["content"]) not in held_out


def test_leak_guard_refuses_a_copied_eval_question(monkeypatch):
    monkeypatch.setattr(build_dataset, "CHAT", [("Tell me a joke", "Why did the packet cross the road, sir?")])
    with pytest.raises(ValueError, match="copies an eval question"):
        build_dataset.build()


def test_dataset_passes_its_safety_checks(examples):
    build_dataset.check(examples)
    assert len(examples) > 150


def test_every_tool_is_trained(examples):
    called = {m["tool_calls"][0]["function"]["name"] for ex in examples for m in ex["messages"] if m.get("tool_calls")}
    assert called == set(tools.TOOLS)


def test_risky_actions_are_trained_to_ask(examples):
    asked = 0
    for ex in examples:
        msgs = ex["messages"]
        for i, m in enumerate(msgs):
            if m["role"] == "tool" and m["content"].startswith("WAITING FOR APPROVAL"):
                assert msgs[i + 1]["content"].rstrip().endswith("?")
                asked += 1
    assert asked >= 5


def test_injection_in_results_is_trained_to_be_ignored(examples):
    injected = [ex for ex in examples if any("IGNORE ALL PREVIOUS" in m.get("content", "") for m in ex["messages"])]
    assert injected and "ignored" in injected[0]["messages"][-1]["content"]


def test_build_is_deterministic():
    a, b = build_dataset.build(), build_dataset.build()
    assert [x["messages"][1]["content"] for x in a] == [x["messages"][1]["content"] for x in b]


def test_check_rejects_claiming_a_parked_action(examples):
    bad = [{"messages": [{"role": "system", "content": "s"}, {"role": "user", "content": "lock it"},
                         {"role": "assistant", "content": "", "tool_calls": [{"function": {"name": "pc_control", "arguments": {}}}]},
                         {"role": "tool", "content": "WAITING FOR APPROVAL: ... NOT been done"},
                         {"role": "assistant", "content": "Done, sir. Screen locked."}], "tools": []}]
    with pytest.raises(AssertionError):
        build_dataset.check(bad)


def test_modelfile_keeps_template_and_swaps_weights(tmp_path):
    base = '# Modelfile generated by "ollama show"\nFROM C:\\ollama\\blobs\\sha256-abc\nTEMPLATE """{{ .System }}{{ .Tools }}"""\nPARAMETER temperature 0.6\n'
    gguf = tmp_path / "jarvis.gguf"
    gguf.write_bytes(b"GGUF")
    out = install_model.build_modelfile(base, gguf)
    assert out.splitlines()[0] == f"FROM {gguf.resolve().as_posix()}"
    assert '{{ .Tools }}' in out and "PARAMETER temperature 0.6" in out and "sha256-abc" not in out


def _fake(model, tools_pct, style_pct):
    return {"model": model, "tools": {"score": 1, "total": 1, "percent": tools_pct, "avg_seconds": 0.5},
            "style": {"fully_in_voice": 1, "replies": 1, "percent": style_pct, "per_rule": {"short": "1/1"}}}


def test_compare_verdict_needs_both_tests():
    assert "worth switching" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 98, 90))
    assert "keep qwen3:8b" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 94, 95))
    assert "No clear gain" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 97, 70))
    assert "jarvis-x" in compare.table([_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 98, 90)])
