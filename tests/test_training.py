def test_modelfile_keeps_template_and_swaps_weights(tmp_path):
    base = '# Modelfile generated by "ollama show"\nFROM C:\\ollama\\blobs\\sha256-abc\nTEMPLATE """{{ .System }}{{ .Tools }}"""\nPARAMETER temperature 0.6\n'
    gguf = tmp_path / "jarvis.gguf"
    gguf.write_bytes(b"GGUF")
    out = install_model.build_modelfile(base, gguf)
    assert out.splitlines()[0] == f"FROM {gguf.resolve().as_posix()}"
    assert '{{ .Tools }}' in out and "PARAMETER temperature 0.6" in out and "sha256-abc" not in out


def _fake(model, tools_pct, style_pct):
    return {"model": model, "tools": {"score": 1, "total": 1, "percent": tools_pct, "avg_seconds": 0.5},
            "style": {"fully_in_voice": 1, "replies": 1, "percent": style_pct, "per_rule": {"short": "1/1"}}}


def test_compare_verdict_needs_both_tests():
    assert "worth switching" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 98, 90))
    assert "keep qwen3:8b" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 94, 95))
    assert "No clear gain" in compare.verdict(_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 97, 70))
    assert "jarvis-x" in compare.table([_fake("qwen3:8b", 97, 70), _fake("jarvis-x", 98, 90)])



