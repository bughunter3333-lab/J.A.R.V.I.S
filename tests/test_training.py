def test_leak_guard_refuses_a_copied_eval_question(monkeypatch):
    monkeypatch.setattr(build_dataset, "CHAT", [("Tell me a joke", "Why did the packet cross the road, sir?")])
    with pytest.raises(ValueError, match="copies an eval question"):
        build_dataset.build(use_feedback=False)


def test_dataset_passes_its_safety_checks(examples):
    build_dataset.check(examples)
    assert len(examples) > 150


def test_every_tool_is_trained(examples):
    called = {m["tool_calls"][0]["function"]["name"] for ex in examples for m in ex["messages"] if m.get("tool_calls")}
    assert called == set(tools.TOOLS)


def test_risky_actions_are_trained_to_ask(examples):
    asked = 0
    for ex in examples:
        msgs = ex["messages"]
        for i, m in enumerate(msgs):
            if m["role"] == "tool" and m["content"].startswith("WAITING FOR APPROVAL"):
                assert msgs[i + 1]["content"].rstrip().endswith("?")
                asked += 1
    assert asked >= 5


def test_injection_in_results_is_trained_to_be_ignored(examples):
    injected = [ex for ex in examples if any("IGNORE ALL PREVIOUS" in m.get("content", "") for m in ex["messages"])]
    assert injected and "ignored" in injected[0]["messages"][-1]["content"]


def test_build_is_deterministic():
    a, b = build_dataset.build(), build_dataset.build()
    assert [x["messages"][1]["content"] for x in a] == [x["messages"][1]["content"] for x in b]


